/* ────────── AI Form Analysis ────────── */

export interface FormAnalysisFrame {
  /** Timestamp in the video (seconds) */
  timestamp: number;
  /** Detected joint positions (normalized 0-1) */
  joints: Record<string, { x: number; y: number; confidence: number }>;
}

export interface FormAnalysisResult {
  /** Overall form quality score (0-100) */
  overallScore: number;
  /** Per-frame analysis */
  frames: FormAnalysisFrame[];
  /** Text feedback from the analysis */
  feedback: string[];
  /** Specific issues detected */
  issues: { severity: 'info' | 'warning' | 'critical'; description: string; timestamp?: number }[];
  /** AI disclosure */
  disclosureText: string;
}

