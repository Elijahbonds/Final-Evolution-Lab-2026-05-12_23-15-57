/* ────────── EU AI Act Disclosure Utilities ────────── */

export const AI_DISCLOSURE_TEXT = 'This content was generated using artificial intelligence and does not represent a real recording of Coach Elijah Bonds.';

export function getAiDisclosureForType(type: SyntheticCoachOutput['type']): string {
  switch (type) {
    case 'audio':
      return 'This voice was generated by AI. It is not a real recording.';
    case 'video':
      return 'This video contains AI-generated content. It is not a real recording of Coach Elijah Bonds.';
    case 'avatar':
      return 'This avatar is AI-generated and does not represent a real-time recording.';
    default:
      return AI_DISCLOSURE_TEXT;
  }
}
