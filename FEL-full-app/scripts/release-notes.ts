#!/usr/bin/env -S npx tsx
// Release notes from the PRs merged since the last release (QG-05, quality-gates lane, 2026-10-25). docs/RELEASE.md is
// the process; lib/release/notes.ts turns PR titles (and `What's new:` lines in PR bodies) into plain language.
//
//   npx tsx scripts/release-notes.ts                         # print the notes for origin/main..origin/lane/finish-release
//   npx tsx scripts/release-notes.ts --from <sha> --to <sha> # any range ("the last release" .. "this deploy")
//   npx tsx scripts/release-notes.ts --bodies                # also read each PR's body through `gh` (its What's new: line)
//   npx tsx scripts/release-notes.ts --write --version "Oct 26"   # add the release to lib/release/releases.json
//   npx tsx scripts/release-notes.ts --deployed <sha>        # mark the release whose sha is <sha> as live (today)
//
// It reads git (and `gh pr view` with --bodies) and writes only lib/release/releases.json. It never tags, pushes or
// deploys: version tags and a preview channel are the owner's (OWN-22).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { buildRelease, parseMergeLog, releaseMarkdown, type MergedPr, type Release } from '../lib/release/notes';

const ROOT = resolve(__dirname, '..');
const RELEASES = join(ROOT, 'lib/release/releases.json');
const arg = (name: string) => { const i = process.argv.indexOf(name); return i >= 0 ? process.argv[i + 1] : undefined; };
const git = (...a: string[]) => execFileSync('git', a, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 << 20 }).trim();

function readReleases(): Release[] {
  try { return JSON.parse(readFileSync(RELEASES, 'utf8')).releases as Release[]; } catch { return []; }
}
function writeReleases(rs: Release[]): void {
  writeFileSync(RELEASES, JSON.stringify({
    _readme: 'Generated by scripts/release-notes.ts (docs/RELEASE.md). /whats-new shows the public notes. Edit a note\'s text here if it reads badly; set public:false to hide one.',
    releases: rs,
  }, null, 2) + '\n');
}

function main(): void {
  const deployed = arg('--deployed');
  if (deployed) {
    const full = git('rev-parse', deployed);
    const rs = readReleases();
    const r = rs.find((x) => full.startsWith(x.sha) || x.sha.startsWith(full));
    if (!r) { console.error(`no release in lib/release/releases.json has sha ${deployed}`); process.exit(1); }
    r.deployedAt = new Date().toISOString().slice(0, 10);
    writeReleases(rs);
    console.log(`marked ${r.version} (${r.sha.slice(0, 8)}) as deployed ${r.deployedAt}`);
    return;
  }
  const to = git('rev-parse', arg('--to') ?? 'origin/lane/finish-release');
  const from = git('rev-parse', arg('--from') ?? readReleases()[0]?.sha ?? 'origin/main');
  if (from === to) { console.log(`nothing merged: ${from.slice(0, 8)} is the tip`); return; }
  const log = git('log', '--merges', '--first-parent', '--date=short', '--format=%H%x1f%ad%x1f%s%x1f%b%x1e', `${from}..${to}`);
  const prs: MergedPr[] = parseMergeLog(log);
  if (process.argv.includes('--bodies')) {
    for (const pr of prs) {
      try { pr.body = execFileSync('gh', ['pr', 'view', String(pr.number), '--json', 'body', '--jq', '.body'], { cwd: ROOT, encoding: 'utf8' }); }
      catch { console.warn(`  (no body for #${pr.number}: gh unavailable or not signed in; the title is used)`); }
    }
  }
  const date = new Date().toISOString().slice(0, 10);
  const r = buildRelease(prs, { version: arg('--version'), date, sha: to, fromSha: from });
  console.log(releaseMarkdown(r));
  console.log(`${prs.length} merged PRs, ${r.notes.filter((n) => n.public).length} in the public notes.`);
  if (process.argv.includes('--write')) {
    const rs = readReleases().filter((x) => x.sha !== r.sha);
    writeReleases([r, ...rs]);
    console.log(`added ${r.version} to lib/release/releases.json (/whats-new shows it; deployedAt stays null until --deployed)`);
  }
}

main();
